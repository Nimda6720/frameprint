export type Person = { id: number; name: string; profile?: string | null; character?: string; job?: string };
export type MediaType = 'movie' | 'tv';
export type FilmMeta = {
  id: number;
  title: string;
  year: number | null;
  poster: string | null;
  backdrop: string | null;
  overview: string;
  runtime: number | null;
  genres: string[];
  countries: string[];
  language: string | null;
  cast: Person[];
  directors: Person[];
  writers: Person[];
  cinematographers: Person[];
  composers: Person[];
  tmdbRating: number | null;
  mediaType?: MediaType;
  seasons?: number;
  episodes?: number;
};
export type Film = {
  key: string;
  title: string;
  year: number | null;
  letterboxdUrl?: string;
  rating: number | null;
  liked: boolean;
  diaryDates: string[];
  dateAdded?: string;
  rewatches: number;
  metadata?: FilmMeta;
};
export type DiscoveryItem = {
  id: number;
  mediaType: MediaType;
  title: string;
  year: number | null;
  poster: string | null;
  backdrop: string | null;
  overview: string;
  tmdbRating: number | null;
  voteCount?: number;
  genres: string[];
  language: string | null;
  metadata?: FilmMeta;
};
export type ImportResult = { films: Film[]; watchlistCount: number; warnings: string[]; fileNames: string[] };
export type EnrichResult = { key: string; metadata: FilmMeta | null; reason?: string; retryable?: boolean };
export type Screen = 'overview' | 'library' | 'people' | 'dna' | 'timeline' | 'wrapped';
